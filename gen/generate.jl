# Regenerate `src/metadata.jl` and the `deckgl` artifact binding for a deck.gl release.
#
#   julia --project=gen gen/generate.jl [version]
#
# Downloads the npm tarball, binds it as a lazy artifact, introspects the bundle
# with `gen/introspect.js` (requires node), and writes the Julia prop tables.

using Pkg.Artifacts, Pkg.PlatformEngines, Downloads, SHA, JSON

const ROOT = dirname(@__DIR__)
const VERSION_ARG = isempty(ARGS) ? "9.3.11" : ARGS[1]
const URL = "https://registry.npmjs.org/deck.gl/-/deck.gl-$VERSION_ARG.tgz"

#-----------------------------------------------------------------------------# Artifact
tarball = Downloads.download(URL)
tarball_sha256 = bytes2hex(open(sha256, tarball))

tree_hash = create_artifact() do dir
    unpack(tarball, dir)
end

bind_artifact!(joinpath(ROOT, "Artifacts.toml"), "deckgl", tree_hash;
    download_info = [(URL, tarball_sha256)], lazy = true, force = true)

@info "bound artifact" tree_hash tarball_sha256

#-----------------------------------------------------------------------------# Introspect
bundle = joinpath(artifact_path(tree_hash), "package", "dist.min.js")
isfile(bundle) || error("bundle not found at $bundle")

meta_json = joinpath(ROOT, "gen", "deckgl-meta.json")
run(`node $(joinpath(ROOT, "gen", "introspect.js")) $bundle $VERSION_ARG $meta_json`)
meta = JSON.parse(read(meta_json, String))

#-----------------------------------------------------------------------------# Emit metadata.jl
symvec(v) = "[" * join((":$x" for x in v), ", ") * "]"

open(joinpath(ROOT, "src", "metadata.jl"), "w") do io
    println(io, """
    # This file is generated by `gen/generate.jl` from deck.gl v$(meta.version). Do not edit.
    # See `gen/README.md` for how each table is derived and what to check on a version bump.

    const DECKGL_VERSION = "$(meta.version)"
    """)

    println(io, "const LAYER_PROPS = Dict{Symbol,Vector{Symbol}}(")
    for (name, spec) in pairs(meta.layers)
        println(io, "    :$name => $(symvec(spec.props)),")
    end
    println(io, ")\n")

    println(io, "const LAYER_ACCESSORS = Dict{Symbol,Vector{Symbol}}(")
    for (name, spec) in pairs(meta.layers)
        println(io, "    :$name => $(symvec(spec.accessors)),")
    end
    println(io, ")\n")

    println(io, "const LAYER_DOCS = Dict{Symbol,String}(")
    for (name, spec) in pairs(meta.layers)
        println(io, "    :$name => \"$(spec.docs)\",")
    end
    println(io, ")\n")

    # Aggregation layers bin their records on the way to the GPU, so they read every
    # one through its accessor and cannot take binary attributes.
    println(io, "const AGGREGATION_LAYERS = Set{Symbol}($(symvec([n for (n, s) in pairs(meta.layers) if s.module == "aggregation-layers"])))\n")

    println(io, "const COMPOSITE_LAYERS = Set{Symbol}($(symvec([n for (n, s) in pairs(meta.layers) if s.composite])))\n")
    println(io, "const LAYER_NAMES = $(symvec(sort(collect(keys(meta.layers)))))\n")

    println(io, "const WIDGET_PROPS = Dict{Symbol,Vector{Symbol}}(")
    for (name, spec) in pairs(meta.widgets)
        println(io, "    :$name => $(symvec(spec.props)),")
    end
    println(io, ")\n")
    println(io, "const WIDGET_NAMES = $(symvec(sort(collect(keys(meta.widgets)))))\n")

    println(io, "const VIEW_PROPS = Dict{Symbol,Vector{Symbol}}(")
    for (name, spec) in pairs(meta.views)
        println(io, "    :$name => $(symvec(spec.props)),")
    end
    println(io, ")\n")

    # Which props hold colors, per class. `color` is RGB(A) on TerrainLayer and a CSS
    # string on IconWidget, so this cannot be decided from the prop name alone.
    println(io, "const COLOR_PROPS = Dict{Symbol,Vector{Symbol}}(")
    for table in (meta.layers, meta.widgets, meta.views), (name, spec) in pairs(table)
        isempty(spec.colors) || println(io, "    :$name => $(symvec(spec.colors)),")
    end
    println(io, ")\n")
    println(io, "const VIEW_NAMES = $(symvec(sort(collect(keys(meta.views)))))")
end

@info "wrote src/metadata.jl"
